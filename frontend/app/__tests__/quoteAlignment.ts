import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import postcss from 'postcss'
import tailwindcss from 'tailwindcss'
import config from '../../tailwind.config'

const QUOTE = join(__dirname, '../components/Paragraph/Quote/index.vue')

// Tailwind generates only the classes it finds written out in the source.
async function generatedUtilities(source: string) {
  const result = await postcss([
    tailwindcss({
      ...config,
      content: [{ raw: source, extension: 'vue' }],
      corePlugins: { preflight: false },
    }),
  ]).process('@tailwind utilities;', { from: undefined })
  return result.css
}

describe('quote alignment', () => {
  it('has its text alignment classes generated by Tailwind', async () => {
    const css = await generatedUtilities(readFileSync(QUOTE, 'utf8'))

    expect(css).toContain('.sm\\:text-left')
    expect(css).toContain('.sm\\:text-right')
  })
})
